#!/usr/bin/env python3
"""Generate docs/spec/fork-table.md and docs/spec/rule-register.md.

Inputs (read only):
  crates/xone-chainspec/generated/forks.json   written by conformance/exporter from the pinned geth-XDC
  spec/**/*.md                                  one page per rule
Usage: python3 docs/spec/gen.py [--check]
  --check  regenerate in memory, exit 1 with a message if a committed file differs.
Standard library only. Run from any directory.
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parent
SENTINEL = "99999999999"
NETS = ["mainnet", "apothem", "net2040", "devnet", "devnet551"]  # display order
GETH = "https://github.com/XDCIndia/go-ethereum"

forks = json.loads((ROOT / "crates/xone-chainspec/generated/forks.json").read_text())
pin = forks["pin"]
assert pin == (ROOT / "conformance/PIN").read_text().strip(), "forks.json pin differs from conformance/PIN"
nets = [n for n in NETS if n in forks["networks"]]
assert set(nets) == set(forks["networks"]), "a network in forks.json is not in NETS"


def cell(v):
    if v is None:
        return "-"
    return "unscheduled" if v == SENTINEL else f"{int(v):,}"


def fork_table():
    o = [
        "# Fork table (generated)",
        "",
        "Do not edit. Generated by `docs/spec/gen.py` from `crates/xone-chainspec/generated/forks.json`,",
        f"which `conformance/exporter` writes from geth-XDC `{pin}`.",
        "`python3 docs/spec/gen.py --check` fails when this file is stale.",
        "",
        "Legend: a number is the first block of the rule; `-` is geth `nil` (the rule is `Never`);",
        f"`unscheduled` is the placeholder {int(SENTINEL):,} (declared, never active; see",
        "[unscheduled-sentinel](../../spec/chainspec/unscheduled-sentinel.md)).",
        "",
        "## Chain ids and genesis",
        "",
        "| Network | Chain id | Genesis hash | State root |",
        "| --- | --- | --- | --- |",
    ]
    for n in nets:
        v = forks["networks"][n]
        o.append(f"| {n} | {v['chainId']} | `{v['genesis']['hash']}` | `{v['genesis']['stateRoot']}` |")
    o += ["", "## Rows of `params.ChainConfig` (every `*Block` field)", "",
          "| Row | " + " | ".join(nets) + " |", "| --- |" + " --- |" * len(nets)]
    keys = sorted({k for n in nets for k in forks["networks"][n]["blocks"]})
    for k in keys:
        if all(forks["networks"][n]["blocks"].get(k) is None for n in nets):
            continue  # all-nil rows are listed below, not in the table
        o.append(f"| `{k}` | " + " | ".join(cell(forks["networks"][n]["blocks"].get(k)) for n in nets) + " |")
    nilrows = [k for k in keys if all(forks["networks"][n]["blocks"].get(k) is None for n in nets)]
    o += ["", "Rows that are `nil` on every network above: " + ", ".join(f"`{k}`" for k in nilrows) + ".", ""]
    o += ["## Effective activation (rules that are not a plain row)", "",
          "The first block at which geth's own predicate holds. A row of the previous table is not the",
          "activation block for these rules. See [non-parameter-switches](../../spec/chainspec/non-parameter-switches.md).",
          "", "| Rule | " + " | ".join(nets) + " |", "| --- |" + " --- |" * len(nets)]
    for k in sorted({k for n in nets for k in forks["networks"][n]["effective"]}):
        o.append(f"| `{k}` | " + " | ".join(cell(forks["networks"][n]["effective"].get(k)) for n in nets) + " |")
    o += ["", "## XDPoS parameters", "",
          "| Parameter | " + " | ".join(nets) + " |", "| --- |" + " --- |" * len(nets)]
    scalars = [k for k in forks["networks"][nets[0]]["xdpos"] if k != "v2"]
    for k in scalars:
        o.append(f"| `{k}` | " + " | ".join(f"`{forks['networks'][n]['xdpos'][k]}`" for n in nets) + " |")
    for k in ("switchBlock", "switchEpoch"):
        o.append(f"| `v2.{k}` | " + " | ".join(f"`{forks['networks'][n]['xdpos']['v2'][k]}`" for n in nets) + " |")
    o += ["", "## V2 parameters by round", ""]
    for n in nets:
        cfgs = forks["networks"][n]["xdpos"]["v2"]["allConfigs"]
        cols = list(next(iter(cfgs.values())))
        o += [f"### {n}", "", "| round | " + " | ".join(cols) + " |", "| --- |" + " --- |" * len(cols)]
        for r in sorted(cfgs, key=int):
            o.append(f"| {r} | " + " | ".join(f"`{cfgs[r][c]}`" for c in cols) + " |")
        o.append("")
    return "\n".join(o)


REF = re.compile(r"`((?:[\w.-]+/)+[\w.-]+\.go):(\d+)(?:-(\d+))?")


def register():
    o = [
        "# Rule register (generated)",
        "",
        "Do not edit. Generated by `docs/spec/gen.py` from the pages under `spec/` and from",
        "`spec/chainspec/non-parameter-switches.md`. `--check` fails when this file is stale.",
        "",
        f"All geth references are to `XDCIndia/go-ethereum` at `{pin}` (the same SHA as `conformance/PIN`,",
        "`crates/xone-chainspec/genesis/PIN` and `generated/forks.json`).",
        "",
        "## Pages",
        "",
        "A page with 0 geth references is a defect (`spec/README.md`: a rule with no source line is not a rule).",
        "",
        "| Page | Rule (title) | geth refs | First geth reference |",
        "| --- | --- | --- | --- |",
    ]
    zero = []
    for p in sorted((ROOT / "spec").rglob("*.md")):
        rel = p.relative_to(ROOT).as_posix()
        if rel == "spec/README.md":
            continue
        t = p.read_text()
        title = next((l[2:].strip() for l in t.splitlines() if l.startswith("# ")), rel)
        refs = REF.findall(t)
        if not refs:
            zero.append(rel)
        first = "-"
        if refs:
            f, a, b = refs[0]
            first = f"[`{f}:{a}{'-' + b if b else ''}`]({GETH}/blob/{pin}/{f}#L{a}{'-L' + b if b else ''})"
        o.append(f"| [{rel[5:]}](../../{rel}) | {title.replace('|', '/')} | {len(refs)} | {first} |")
    o += ["", f"Pages without a geth reference: {len(zero)}" + (": " + ", ".join(zero) if zero else "") + ".", ""]
    # switches: copy the tables A-D rows (id, rule, geth, rust) from the page
    sw = (ROOT / "spec/chainspec/non-parameter-switches.md").read_text().splitlines()
    rows = [l for l in sw if re.match(r"\| [A-D]\d+ \|", l)]
    o += ["## Non-parameter switches", "",
          "Copied by row from [non-parameter-switches](../../spec/chainspec/non-parameter-switches.md)",
          "(sections A to D). Gaps G2 to G4 on that page are the switches with no Rust representation yet.", "",
          "| # | Rule | geth at the pin | Networks or effect | Rust |", "| --- | --- | --- | --- | --- |"]
    for l in rows:
        c = [x.strip() for x in l.strip().strip("|").split("|")]
        if len(c) == 5:
            o.append("| " + " | ".join(c) + " |")
        elif len(c) == 4:  # section D has no Rust column
            o.append(f"| {c[0]} | {c[1]} | {c[2]} | {c[3]} | none (no table value) |")
    o.append("")
    return "\n".join(o), len(zero)


def main():
    files = {"fork-table.md": fork_table() + "\n"}
    reg, _ = register()
    files["rule-register.md"] = reg
    if "--check" in sys.argv:
        bad = [n for n, s in files.items() if not (OUT / n).exists() or (OUT / n).read_text() != s]
        if bad:
            print("stale (run python3 docs/spec/gen.py): " + ", ".join(bad))
            sys.exit(1)
        print("docs/spec generated files are current")
        return
    for n, s in files.items():
        (OUT / n).write_text(s)
        print("wrote", OUT / n)


main()
