"""Unsafe/FFI audit of the release tree of `xone` (normal + build dependencies, Linux).

Usage: cargo metadata ... | python3 -I ci/unsafe-audit.py <tree-file> > docs/assurance/<file>.md
<tree-file> is `cargo tree -p xone -e normal,build --prefix none --locked`: the exact package
set the build uses (cargo metadata alone unifies features across the whole workspace and
over-reports). The metadata only supplies paths, sources and manifests.
Counts the word `unsafe` in non-comment lines of each package's src/ (and build.rs),
read from the vendored registry sources. An approximation: it counts blocks, fns,
impls and traits alike, and macro-generated unsafe is invisible. FFI = `extern "..."`
blocks or fns, `#[link`, a `links =` key, or a `-sys` package.
"""
import collections
import json
import os
import re
import sys

meta = json.load(sys.stdin)
real = set()
for line in open(sys.argv[1]):
    m = re.match(r"(\S+) v(\S+)", line)
    if m:
        real.add((m.group(1), m.group(2)))
pk = {p["id"]: p for p in meta["packages"] if (p["name"], p["version"]) in real}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"] if n["id"] in pk}
root = next(p["id"] for p in meta["packages"] if p["name"] == "xone")

parent = {root: None}
queue = collections.deque([root])
while queue:
    cur = queue.popleft()
    for d in nodes[cur]["deps"]:
        if d["pkg"] in pk and any(k["kind"] in (None, "build") for k in d["dep_kinds"]) and d["pkg"] not in parent:
            parent[d["pkg"]] = cur
            queue.append(d["pkg"])


def path_of(i):
    out = []
    while i:
        out.append(pk[i]["name"])
        i = parent[i]
    return " > ".join(reversed(out))


UNSAFE = re.compile(r"\bunsafe\b")
FFI = re.compile(r'\bextern\s+"[^"]*"|#\[\s*link\b')
rows = []
for i in parent:
    p = pk[i]
    d = os.path.dirname(p["manifest_path"])
    files = [os.path.join(d, "build.rs")]
    for base, dirs, names in os.walk(os.path.join(d, "src")):
        files += [os.path.join(base, n) for n in names if n.endswith(".rs")]
    n_unsafe, ffi = 0, p["name"].endswith("-sys") or bool(p.get("links"))
    for f in files:
        if not os.path.isfile(f):
            continue
        for line in open(f, encoding="utf-8", errors="replace"):
            code = line.split("//", 1)[0]
            n_unsafe += len(UNSAFE.findall(code))
            ffi = ffi or bool(FFI.search(code))
    local = p["source"] is None
    why = "this repository" if i == root else ("direct dependency of xone" if parent[i] == root else "via " + path_of(i))
    rows.append((p["name"], p["version"], n_unsafe, ffi, why, local))

rows.sort(key=lambda r: (-r[2], r[0]))
print("# Unsafe and FFI audit of the `xone` release tree, 2026-11-11\n")
print("Generated by `ci/unsafe-audit.sh`. Scope: normal and build dependencies of `bin/xone` on")
print("`x86_64-unknown-linux-gnu`, read from the vendored sources in `~/.cargo/registry/src`.\n")
assert len(rows) == len(real), (len(rows), len(real))
print(f"Packages: {len(rows)}. With any `unsafe`: {sum(1 for r in rows if r[2])}. "
      f"Unsafe tokens in total: {sum(r[2] for r in rows)}. With FFI: {sum(1 for r in rows if r[3])}.\n")
print("The count is the word `unsafe` outside `//` comments in `src/` and `build.rs`. It is a measure of")
print("review effort, not of risk, and it cannot see unsafe that a macro generates. `cargo geiger`")
print("was not used (see the script header). Workspace crates are marked local; `forbid(unsafe_code)` holds there.\n")
print("| crate | version | unsafe count | FFI | reason it is in the tree | owner review |")
print("|---|---|---:|---|---|---|")
for name, ver, n, ffi, why, local in rows:
    print(f"| {name}{' (local)' if local else ''} | {ver} | {n} | {'yes' if ffi else 'no'} | {why} | pending |")
